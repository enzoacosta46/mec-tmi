.include "m328pdef.inc"

;------------------------------------------------------------
; Vector de RESET
;------------------------------------------------------------
.cseg
.org 0x0000
    rjmp inicio


;------------------------------------------------------------
; Inicialización
;------------------------------------------------------------
inicio:

    ; Inicialización del Stack Pointer
    ldi r16, HIGH(RAMEND)
    out SPH, r16

    ldi r16, LOW(RAMEND)
    out SPL, r16


;------------------------------------------------------------
; Programa principal
;------------------------------------------------------------
main:
    rjmp main